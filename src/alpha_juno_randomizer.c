static uint32_t xorshift32(uint32_t x)
{
    if (x == 0) x = 1;
    x ^= x << 13;
    x ^= x >> 17;
    x ^= x << 5;
    return x;
}

size_t aj_build_param_sysex(uint8_t out[10], uint8_t midi_channel, uint8_t param, uint8_t value)
{
    out[0] = 0xF0; out[1] = 0x41; out[2] = 0x36; out[3] = midi_channel & 0x0F;
    out[4] = 0x23; out[5] = 0x20; out[6] = 0x01; out[7] = param; out[8] = value; out[9] = 0xF7;
    return 10;
}

bool aj_randomizer_generate(
    uint8_t command,
    uint8_t midi_channel,
    uint32_t seed,
    const aj_randomizer_io_t *io)
{
    if (io == NULL || io->send_param == NULL || command >= 16) return false;
    int recipe = k_command_to_recipe[command];
    if (recipe < 0) return false;

    const bool mono = (recipe == 4 || recipe == 5);
    if (io->send_voice_mode != NULL) io->send_voice_mode(io->ctx, midi_channel & 0x0F, mono);

    uint32_t rng = seed ^ ((uint32_t)recipe << 24) ^ 0x6D2B79F5u;
    if (rng == 0) rng = 1;

    for (uint8_t param = 0; param < AJ_PARAM_COUNT; ++param) {
        const range8_t r = k_recipes[recipe][param];
        rng = xorshift32(rng);
        uint8_t value = r.lo;
        if (r.hi != r.lo) {
            const uint32_t span = (uint32_t)r.hi - (uint32_t)r.lo + 1u;
            value = (uint8_t)(r.lo + (rng % span));
        }

        if (param == 11 && recipe >= 4 && recipe <= 6) value = 0;
        if (param == 9 || param == 22) continue;

        io->send_param(io->ctx, midi_channel & 0x0F, param, value);
    }

    return true;
}
